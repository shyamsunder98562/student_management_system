    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
        String studentRollnumber=sRollNumber.getText();
        DefaultTableModel model =(DefaultTableModel)Table.getModel();
        if(studentRollnumber.isEmpty()){
            JOptionPane.showMessageDialog(this,"Plese enter RollNumber : ");
        }
        try{
            model.setRowCount(0);
              //lode deiver
           Class.forName("com.mysql.cj.jdbc.Driver");
            //connection
            Connection con =DriverManager.getConnection("jdbc:mysql://localhost:3306/college","root","123456");
            //create query
            String query="SELECT * FROM students WHERE RollNumber=?";
            PreparedStatement pstmt=con.prepareStatement(query);
            pstmt.setString(1, studentRollnumber);
            ResultSet rs=pstmt.executeQuery();
             
            boolean hasResult=false;
             while(rs.next()){
                 hasResult=true;
                int sRollnumber=rs.getInt("RollNumber");
                String StudentRollnumber=Integer.toString(sRollnumber);
                String StudentName=rs.getString("StudentName");
                String ClassName=rs.getString("Class");
                String row[] = {StudentRollnumber,StudentName,ClassName};
                model.addRow(row);
            }
            if(!hasResult){
                JOptionPane.showMessageDialog(this,"No result found ");
            }  
        }catch(Exception e){
            JOptionPane.showMessageDialog(this,e);
           
        } 
    }//GEN-LAST:event_jButton3ActionPerformed

